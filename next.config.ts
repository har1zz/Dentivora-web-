import type { NextConfig } from "next";

const isDev = process.env.NODE_ENV === "development";

// Strict static CSP. 'unsafe-inline' is required for Next's inline bootstrap scripts
// without per-request nonces; everything else is locked to our own origin plus the
// MyChatBot widget host and Supabase (add hosts here if you add more integrations).
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""} https://storage.googleapis.com/mychatbot-widget-assets/`,
  "style-src 'self' 'unsafe-inline' https://storage.googleapis.com/mychatbot-widget-assets/",
  "img-src 'self' data: blob: https://images.unsplash.com https://*.supabase.co https://api.mychatbot.app https://storage.googleapis.com",
  "font-src 'self' data: https://storage.googleapis.com",
  "media-src 'self' blob: https://*.supabase.co",
  "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://api.mychatbot.app wss://api.mychatbot.app",
  "frame-src 'self' https://api.mychatbot.app https://www.openstreetmap.org",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  reactStrictMode: true,
  images: {
    formats: ["image/avif", "image/webp"],
    remotePatterns: [{ protocol: "https", hostname: "images.unsplash.com" }],
  },
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders },
      { source: "/admin/:path*", headers: [{ key: "Cache-Control", value: "no-store" }] },
      { source: "/api/:path*", headers: [{ key: "Cache-Control", value: "no-store" }] },
    ];
  },
  turbopack: {
    rules: {
      "*.css": { loaders: ["@tailwindcss/turbopack"], as: "*.css" },
    },
  },
};

export default nextConfig;
